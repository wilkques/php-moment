// Builds data/guess-abbrs.php: the host abbreviation tz.guess() scores, per zone name, as V8 prints it from ICU's
// English long name (toTimeString(): "(Central Standard Time)" -> CST). Lets Tz::guess() match without ext-intl.
// Run in a Node with full ICU: node tools/generate-guess-abbrs.js php-identifiers.json
// (the JSON list is DateTimeZone::listIdentifiers(DateTimeZone::ALL_WITH_BC) from PHP, so every name PHP can report is covered)
var fs = require('fs');
var path = require('path');
var mtz = require('moment-timezone');

var names = {};
mtz.tz.names().forEach(function (n) { names[n] = true; });
if (process.argv[2]) {
    JSON.parse(fs.readFileSync(process.argv[2], 'utf8')).forEach(function (n) { names[n] = true; });
}

function abbr(long) {
    var timeString = '12:00:00 GMT+0000 (' + long + ')', m, caps;
    if ((m = timeString.match(/\([a-z ]+\)/i))) {
        caps = m[0].match(/[A-Z]/g);
        m = caps ? caps.join('') : null;
    } else {
        m = timeString.match(/[A-Z]{3,5}/g);
        m = m ? m[0] : null;
    }
    return m === 'GMT' ? null : m;
}

function info(name, date) {
    var parts = new Intl.DateTimeFormat('en-US', {timeZone: name, timeZoneName: 'long'}).formatToParts(date);
    var off = new Intl.DateTimeFormat('en-US', {timeZone: name, timeZoneName: 'longOffset'}).formatToParts(date);
    var long = parts.filter(function (p) { return p.type === 'timeZoneName'; })[0].value;
    var o = off.filter(function (p) { return p.type === 'timeZoneName'; })[0].value.match(/([+-])(\d\d):(\d\d)/);
    return {abbr: abbr(long), offset: o ? (o[1] === '-' ? -1 : 1) * (+o[2] * 60 + +o[3]) : 0};
}

var year = new Date().getUTCFullYear(), table = {}, skipped = [];
Object.keys(names).sort().forEach(function (name) {
    try {
        var jan = info(name, new Date(Date.UTC(year, 0, 1, 12))), jul = info(name, new Date(Date.UTC(year, 6, 1, 12)));
    } catch (e) {
        skipped.push(name);
        return;
    }
    var dst = jul.offset > jan.offset ? jul : jan.offset > jul.offset ? jan : null;
    var std = dst === jul ? jan : jul;
    table[name] = [std.abbr, dst ? dst.abbr : std.abbr];
});

function q(s) { return s === null ? 'null' : "'" + s + "'"; }
var lines = Object.keys(table).sort().map(function (n) {
    return "    '" + n + "' => array(" + q(table[n][0]) + ', ' + q(table[n][1]) + '),\n';
});
fs.writeFileSync(path.join(__dirname, '..', 'data', 'guess-abbrs.php'),
    '<?php\n\n// Generated by tools/generate-guess-abbrs.js from ICU ' + process.versions.icu +
    ' (Node ' + process.version + '). Do not edit.\n// zone name => array(standard, daylight) host abbreviation, null when ICU has no ASCII one (GMT+01:00).\n\nreturn array(\n' +
    lines.join('') + ');\n');
console.log('icu', process.versions.icu, 'entries', lines.length, 'unknown to Intl', skipped.length, skipped.join(' '));
