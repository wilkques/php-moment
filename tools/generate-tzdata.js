// Converts moment-timezone's packed data to data/latest.php. Run: node tools/generate-tzdata.js
var fs = require('fs');
var path = require('path');
var pkg = require('moment-timezone/package.json');
var d = require('moment-timezone/data/packed/latest.json');

function q(s) { return "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'"; }
function arr(a) { return 'array(\n' + a.map(function (x) { return '        ' + q(x) + ',\n'; }).join('') + '    )'; }

var out = '<?php\n\n// Generated by tools/generate-tzdata.js from moment-timezone ' + pkg.version +
    ' data/packed/latest.json. Do not edit.\n\nreturn array(\n    \'version\' => ' + q(d.version) +
    ',\n    \'zones\' => ' + arr(d.zones) + ',\n    \'links\' => ' + arr(d.links) +
    ',\n    \'countries\' => ' + arr(d.countries) + ',\n);\n';
fs.writeFileSync(path.join(__dirname, '..', 'data', 'latest.php'), out);
console.log(d.version, d.zones.length, d.links.length, d.countries.length);
